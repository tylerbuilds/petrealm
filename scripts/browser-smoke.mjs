import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import { readFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const {name} = JSON.parse(await readFile('package.json', 'utf8'));
const port = 4322;
const server = spawn(process.execPath, ['scripts/serve.mjs', '--dir', 'dist', '--port', String(port)], {stdio:['ignore','pipe','pipe']});
let serverOutput = '';
server.stdout.on('data', chunk => {serverOutput += chunk});
server.stderr.on('data', chunk => {serverOutput += chunk});
const output = resolve('test-results/browser-smoke');
await mkdir(output, {recursive:true});
let browser;
try {
  let ready = false;
  for (let attempt = 0; attempt < 40; attempt++) {
    try {ready = (await fetch(`http://127.0.0.1:${port}/`)).ok} catch {}
    if (ready) break;
    await new Promise(resolve => setTimeout(resolve, 150));
  }
  if (!ready || server.exitCode !== null) throw new Error(`Preview server failed: ${serverOutput}`);
  browser = await chromium.launch({headless:true, ...(process.env.BROWSER_EXECUTABLE ? {executablePath:process.env.BROWSER_EXECUTABLE} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:960},locale:'en-GB'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if (message.type() === 'error') errors.push(message.text())});
  const response = await page.goto(`http://127.0.0.1:${port}/`, {waitUntil:'networkidle'});
  expect(response.status()).toBe(200);
  const click = async selector => {
    const target = page.locator(selector);
    const disclosure = await target.evaluate(node => node.closest('details')?.id || null);
    if (disclosure && !(await page.locator(`#${disclosure}`).evaluate(node => node.open))) await page.locator(`#${disclosure} > summary`).click();
    await target.click();
  };
  const download = async (selector, filename) => {
    const pending = page.waitForEvent('download');
    await click(selector);
    const file = await pending;
    expect(await file.failure()).toBeNull();
    const path = resolve(output, filename); await file.saveAs(path); return readFile(path);
  };
  if (name === 'clearcv') {
    await page.locator('#profile-name').fill('Avery Test');
    await expect(page.locator('#cv-preview .cv-name')).toHaveText('Avery Test');
    await page.locator('#tab-design').click();
    await page.locator('#template-classic').click();
    await expect(page.locator('#cv-preview')).toHaveClass(/template-classic/);
    await page.reload();
    await expect(page.locator('#cv-preview .cv-name')).toHaveText('Avery Test');
    const saved = JSON.parse((await download('#export-json','cv.json')).toString());
    expect(saved.profile.name).toBe('Avery Test');
    expect(saved.style.template).toBe('classic');
    const pdf = await page.pdf({path:resolve(output,'cv.pdf'),format:'A4',printBackground:true});
    expect(pdf.subarray(0,4).toString()).toBe('%PDF');
  } else if (name === 'stencil-studio') {
    await page.locator('#document-title').fill('Avery design');
    await page.locator('#document-title').press('Tab');
    await page.locator('#elements-tab').click();
    const before = await page.locator('[data-element-id]').count();
    await page.locator('#add-rectangle').click();
    await expect(page.locator('[data-element-id]')).toHaveCount(before + 1);
    await page.locator('#undo').click();
    await expect(page.locator('[data-element-id]')).toHaveCount(before);
    await page.locator('#redo').click();
    await expect(page.locator('[data-element-id]')).toHaveCount(before + 1);
    await page.reload();
    await expect(page.locator('#document-title')).toHaveValue('Avery design');
    const svg = (await download('#export-svg','design.svg')).toString();
    expect(svg).toMatch(/<svg[^>]+xmlns=/);
    const png = await download('#export-png','design.png');
    expect(png.subarray(0,8).toString('hex')).toBe('89504e470d0a1a0a');
    const saved = JSON.parse((await download('#save-document','design.json')).toString());
    expect(saved.title).toBe('Avery design');
  } else if (name === 'petrealm') {
    await page.locator('#pet-name').fill('Aster');
    await page.locator('#adopt-button').click();
    await expect(page.locator('#adoption-dialog')).not.toBeVisible();
    await expect(page.locator('#pet-profile')).toContainText('Aster');
    await expect(page.locator('.scene-card')).toBeVisible();
    await expect(page.locator('#care-play')).toBeVisible();
    await page.locator('#satchel-button').click();
    await page.locator('#daily-reward').click();
    await expect(page.locator('#daily-reward')).toBeDisabled();
    await page.locator('#close-satchel').click();
    await page.reload();
    await expect(page.locator('#pet-profile')).toContainText('Aster');
    await page.locator('#satchel-button').click();
    await expect(page.locator('#daily-reward')).toBeDisabled();
    await page.locator('#close-satchel').click();
    await click('#adopt-another');
    await page.locator('[data-species="emberkit"]').click();
    await page.locator('#pet-name').fill('Nova');
    await page.locator('#adopt-button').click();
    await expect(page.locator('#adoption-dialog')).not.toBeVisible();
    await expect(page.locator('#pet-profile')).toContainText('Nova');
    await page.locator('.nav-button[data-area="realm"]').click();
    await expect(page.locator('.world-map')).toBeVisible();
    await expect(page.locator('.map-node')).toHaveCount(5);
    await expect(page.locator('.quest-journal [data-claim-quest^="daily-"]')).toHaveCount(5);
    await expect(page.locator('#quest-day-complete')).toBeDisabled();
    await page.locator('[data-claim-quest="growing-family"]').click();
    await expect(page.locator('[data-claim-quest="growing-family"]')).toBeDisabled();
    await expect(page.locator('#wallet')).toHaveText('190');
    await page.locator('.nav-button[data-area="market"]').click();
    await page.locator('#bank-amount').fill('25');
    await page.locator('#bank-deposit').click();
    await expect(page.locator('#wallet')).toHaveText('165');
    await expect(page.locator('#bank-balance')).toContainText('25');
    await expect(page.locator('#bank-interest')).toContainText('Collect 1 pebble');
    await page.locator('#bank-interest').click();
    await expect(page.locator('#bank-balance')).toHaveText('26');
    await expect(page.locator('#wallet')).toHaveText('165');
    await expect(page.locator('#bank-interest')).toBeDisabled();
    await page.locator('#bank-amount').fill('10');
    await page.locator('#bank-withdraw').click();
    await expect(page.locator('#wallet')).toHaveText('175');
    await page.locator('.nav-button[data-area="glen"]').click();
    await page.locator('[data-game-mode="memory"]').click();
    await page.locator('#memory-start').click();
    await expect(page.locator('#memory-start')).toBeDisabled();
    await expect(page.locator('[data-memory-index]')).toHaveCount(12);
    await page.locator('[data-memory-index="0"]').click();
    await expect(page.locator('[data-memory-index="0"]')).toHaveClass(/face-up/);
    await page.locator('[data-memory-index="1"]').click();
    await expect(page.locator('#memory-moves')).toHaveText('1 turns');
    await page.locator('.nav-button[data-area="garden"]').click();
    await page.reload();
    await expect(page.locator('#pet-profile')).toContainText('Nova');
    await page.locator('#save-button').click();
    const saved = JSON.parse((await download('#export-save','petrealm.json')).toString());
    expect(saved.version).toBe(2);
    expect(saved.pets.map(pet => pet.name)).toEqual(['Aster','Nova']);
    expect(saved.pets.find(pet => pet.id === saved.activePetId).name).toBe('Nova');
    expect(saved.bank.balance).toBe(16);
    expect(saved.bank.interestClaims).toBe(1);
    expect(saved.bank.interestEarned).toBe(1);
    expect(saved.bank.tier).toBe('seedling');
    expect(saved.questLog.progress.purchases).toBe(0);
    expect(saved.wallet).toBe(175);
    expect(saved.quests.claimed).toContain('growing-family');
    await page.locator('#close-save').click();
    await page.locator('.nav-button[data-area="market"]').click();
    await expect(page.locator('#bank-interest')).toBeDisabled();
    await page.locator('.nav-button[data-area="realm"]').click();
    await page.locator('#lodge-membership').click();
    await expect(page.locator('.quest-journal [data-claim-quest^="daily-"]')).toHaveCount(6);
    await page.locator('#lodge-parcel').click();
    await page.locator('[data-claim-quest="daily-parcel"]').click();
    await expect(page.locator('[data-claim-quest="daily-parcel"]')).toBeDisabled();
    await expect(page.locator('#quest-day-claimed')).toHaveText('1 claimed · 5 needed');
    await expect(page.locator('#quest-day-complete')).toBeDisabled();
    // Exercise the built 0.4 companion UI using the same earned world.
    await page.locator('.nav-button[data-area="garden"]').click();
    await click('#adopt-another');
    await expect(page.locator('#species-options [data-species]')).toHaveCount(9);
    await page.locator('[data-species="thistlehorn"]').click();
    await expect(page.locator('[data-species="thistlehorn"]')).toHaveAttribute('aria-pressed','true');
    await expect(page.locator('#adoption-preview [data-creature]')).toHaveAttribute('data-creature','thistlehorn');
    await page.locator('#pet-personality').selectOption('spirited');
    await page.locator('#pet-name').fill('Bramble');
    await page.locator('#adopt-button').click();
    await expect(page.locator('#pet-profile')).toContainText('Bramble');
    const world=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('petrealm.save.v1')));
    const chosen=s=>s.pets.find(p=>p.id===s.activePetId);
    expect(chosen(await world()).personality).toBe('spirited');
    await page.locator('.nav-button[data-area="garden"]').click();
    await page.locator('#feed-berry').click();
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('petrealm.save.v1')).pets.find(p=>p.name==='Bramble').journey.feeds===1);
    await page.locator('#care-play').click();
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('petrealm.save.v1')).pets.find(p=>p.name==='Bramble').journey.plays===1);
    await page.locator('#care-rest').click();
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('petrealm.save.v1')).pets.find(p=>p.name==='Bramble').journey.rests===1);
    await page.locator('#growth-disclosure summary').click();
    await expect(page.locator('#pet-grow')).toBeDisabled();
    await page.locator('.nav-button[data-area="arena"]').click();
    const beforePractice=await world();
    await page.locator('#pet-train').click();
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('petrealm.save.v1')).pets.find(p=>p.name==='Bramble').journey.trainings===1);
    const practised=await world();
    expect(practised.wallet).toBe(beforePractice.wallet-20);
    expect(chosen(practised).xp).toBe(chosen(beforePractice).xp+18);
    const elapsedHours=(practised.lastUpdated-beforePractice.lastUpdated)/3600000;
    expect(chosen(practised).stats.energy).toBeCloseTo(chosen(beforePractice).stats.energy-12-elapsedHours,9);
    for(let i=0;i<2;i++){
      const previous=beforePractice.pets[i],current=practised.pets[i];
      expect({...current,stats:previous.stats}).toEqual(previous);
      for(const[stat,rate]of[['satiety',3],['happiness',2],['energy',1]])expect(current.stats[stat]).toBeCloseTo(Math.max(0,previous.stats[stat]-rate*elapsedHours),9);
    }
    await page.reload();
    expect(chosen(await world()).journey).toEqual(chosen(practised).journey);
    await page.locator('#save-button').click();
    const companionSave=JSON.parse((await download('#export-save','companions-0.4.json')).toString());
    expect(companionSave.pets.map(p=>p.name)).toEqual(['Aster','Nova','Bramble']);
    expect(chosen(companionSave).species).toBe('thistlehorn');
    expect(chosen(companionSave).personality).toBe('spirited');
    expect(chosen(companionSave).journey).toEqual(chosen(practised).journey);
    await page.locator('#close-save').click();
  } else throw new Error(`Unknown app: ${name}`);
  await page.screenshot({path:resolve(output,'desktop.png'),fullPage:true,animations:'disabled'});
  expect(errors, 'browser errors').toEqual([]);
  console.log(`${name}: built-app edit, persistence and export browser smoke passed`);
} finally {
  if (browser) await browser.close();
  server.kill('SIGTERM');
}
